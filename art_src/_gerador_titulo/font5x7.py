ACC = {'Â': ('A', 'hat'), 'Á': ('A', 'acute'), 'Í': ('I', 'acute'), 'É': ('E', 'acute'),
       'Ã': ('A', 'tilde'), 'Ç': ('C', 'cedil'), 'Ó': ('O', 'acute'), 'Ê': ('E', 'hat')}


def width(text):
    w = 0
    for ch in text:
        base = ACC.get(ch, (ch,))[0]
        w += len(G[base][0]) + 1
    return max(0, w - 1)


def draw(canvas, x, y, text, col, outline=None):
    """y = topo das maiusculas; acentos ocupam y-2..y-1."""
    pts = []
    cx = x
    for ch in text:
        base, mark = (ACC[ch] if ch in ACC else (ch, None))
        g = G[base]
        for j, row in enumerate(g):
            for i, b in enumerate(row):
                if b == '1':
                    pts.append((cx + i, y + j))
        w = len(g[0])
        mid = cx + w // 2
        if mark == 'hat':
            pts += [(mid - 1, y - 1), (mid, y - 2), (mid + 1, y - 1)]
        elif mark == 'acute':
            pts += [(mid, y - 1), (mid + 1, y - 2)]
        elif mark == 'tilde':
            pts += [(mid - 1, y - 1), (mid, y - 2), (mid + 1, y - 1), (mid + 2, y - 2)]
        elif mark == 'cedil':
            pts += [(mid, y + 7), (mid - 1, y + 8)]
        cx += w + 1
    if outline:
        s = set(pts)
        for px, py in pts:
            for dx in (-1, 0, 1):
                for dy in (-1, 0, 1):
                    q = (px + dx, py + dy)
                    if q not in s:
                        canvas.set(q[0], q[1], outline)
    for px, py in pts:
        canvas.set(px, py, col)
    return cx - x - 1
